#!/usr/bin/env node
/**
 * Precompute the portfolio Sectors/Services checkbox options from the tags
 * collection into a static `tina/tag-options.ts`.
 *
 * Why a static file: tina/config.ts is bundled and evaluated in the BROWSER for
 * the admin UI, where Node's `fs` is unavailable. Reading the tag files at
 * config-eval time therefore yields empty options in the browser (blank
 * checkbox groups). Baking the options into a plain TS module that config.ts
 * imports makes them available in both Node (schema generation) and the browser.
 *
 * Runs automatically before `dev:site` and `build:admin`.
 *
 * Usage: node scripts/generate-tag-options.mjs
 */

import { readdir, readFile, writeFile } from "fs/promises";
import { join, dirname } from "path";
import { fileURLToPath } from "url";
import matter from "gray-matter";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const TAGS_DIR = join(ROOT, "src", "content", "tags");
const OUT = join(ROOT, "tina", "tag-options.ts");

function refToSlug(ref) {
  if (!ref || typeof ref !== "string") return "";
  const base = ref.split("/").pop() ?? ref;
  return base.replace(/\.(md|mdx|json)$/i, "");
}

async function main() {
  const files = (await readdir(TAGS_DIR)).filter((f) => f.endsWith(".md"));
  const tags = [];
  for (const f of files) {
    const { data } = matter(await readFile(join(TAGS_DIR, f), "utf-8"));
    tags.push({
      slug: f.replace(/\.md$/, ""),
      label: data.label ?? f.replace(/\.md$/, ""),
      parent: refToSlug(data.parent ?? ""),
      order: typeof data.order === "number" ? data.order : 999,
    });
  }

  const bySlug = new Map(tags.map((t) => [t.slug, t]));
  const rootOf = (slug) => {
    let current = bySlug.get(slug);
    const seen = new Set([slug]);
    while (current?.parent && !seen.has(current.parent)) {
      seen.add(current.parent);
      const next = bySlug.get(current.parent);
      if (!next) return current.parent;
      current = next;
    }
    return current ? current.slug : slug;
  };
  const forRoot = (root) =>
    tags
      .filter((t) => t.slug !== root && rootOf(t.slug) === root)
      .sort((a, b) => a.order - b.order || a.label.localeCompare(b.label))
      .map((t) => ({ value: t.slug, label: t.label }));

  const tagOptions = { sectors: forRoot("portfolio"), services: forRoot("services") };

  const out = `// AUTO-GENERATED by scripts/generate-tag-options.mjs — do not edit by hand.
// Regenerated before dev/build from the tags in src/content/tags.
export type TagOption = { value: string; label: string };
export const tagOptions: { sectors: TagOption[]; services: TagOption[] } = ${JSON.stringify(
    tagOptions,
    null,
    2
  )};
`;
  await writeFile(OUT, out, "utf-8");
  console.log(
    `Wrote tina/tag-options.ts (sectors: ${tagOptions.sectors.length}, services: ${tagOptions.services.length})`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
