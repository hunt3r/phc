/**
 * Generate a static `tag slug -> public URL` map for the TinaCMS `tags`
 * collection router.
 *
 * A collection `ui.router` runs synchronously inside the browser admin bundle
 * and only receives the clicked document, so it cannot walk the tag hierarchy
 * (which decides whether a tag lives under `/portfolio/<slug>` or
 * `/services/<slug>`). This script precomputes the mapping from the content on
 * disk using the same root/href rules as `src/lib/tags.ts`, and writes it to
 * `tina/tag-routes.ts`, which the Tina config imports.
 *
 * Re-run after adding/moving tags or changing the tag hierarchy:
 *   npm run generate:tag-routes
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';

const __dirname = dirname(fileURLToPath(import.meta.url));
const TAGS_DIR = join(__dirname, '..', 'src', 'content', 'tags');
const OUT_FILE = join(__dirname, '..', 'tina', 'tag-routes.ts');

// Mirror of ROOT_ROUTES in src/lib/tags.ts.
const ROOT_ROUTES = {
  portfolio: { hub: '/portfolio', leafBase: '/portfolio' },
  services: { hub: '/services', leafBase: '/services' },
};
const DEFAULT_LEAF_BASE = '/tags';

const refToSlug = (ref) => {
  if (!ref || typeof ref !== 'string') return '';
  const base = ref.split('/').pop() ?? ref;
  return base.replace(/\.(md|mdx|json)$/i, '');
};

// Build slug -> { parent } map.
const tags = new Map();
for (const file of readdirSync(TAGS_DIR)) {
  if (!file.endsWith('.md')) continue;
  const slug = file.replace(/\.md$/, '');
  const { data } = matter(readFileSync(join(TAGS_DIR, file), 'utf8'));
  tags.set(slug, { parent: refToSlug(data.parent ?? '') });
}

const rootAncestor = (slug) => {
  const visited = new Set([slug]);
  let current = slug;
  while (true) {
    const node = tags.get(current);
    const parent = node?.parent;
    if (!parent || visited.has(parent)) return current;
    visited.add(parent);
    current = parent;
  }
};

const hrefFor = (slug) => {
  if (ROOT_ROUTES[slug]) return ROOT_ROUTES[slug].hub;
  const root = rootAncestor(slug);
  const base = ROOT_ROUTES[root]?.leafBase ?? DEFAULT_LEAF_BASE;
  return `${base}/${slug}`;
};

const routes = {};
for (const slug of [...tags.keys()].sort()) {
  routes[slug] = hrefFor(slug);
}

const body = `// AUTO-GENERATED by scripts/generate-tag-routes.mjs — do not edit by hand.
// Maps each tag slug to its public URL, so the TinaCMS \`tags\` collection
// router can open the correct page for visual editing. Regenerate with
// \`npm run generate:tag-routes\` after changing the tag hierarchy.
export const tagRoutes: Record<string, string> = ${JSON.stringify(routes, null, 2)};
`;

writeFileSync(OUT_FILE, body);
console.log(`Wrote ${Object.keys(routes).length} tag routes to ${OUT_FILE}`);
